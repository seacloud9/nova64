import { TestRunner, Assert } from './test-runner.js';
import { executeStudioCartCode } from '../runtime/studio-executor.js';
import { createStudioCartFunction, stripTopLevelExports } from '../runtime/studio-executor.js';
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import assert from 'node:assert/strict';
import { NAMESPACE_MAP } from '../runtime/namespace.js';

export async function runStudioExecutorTests() {
  const runner = new TestRunner();

  runner.test(
    'README first cart executes in Studio without legacy globals or browser print',
    () => {
      const readme = readFileSync(new URL('../README.md', import.meta.url), 'utf8');
      const section = readme.split('## 🎨 **Creating Your First 3D Cart**')[1];
      const source = section.match(/```javascript\n([\s\S]*?)```/)[1];
      const calls = [];
      const nova64 = Object.fromEntries(
        Object.entries(NAMESPACE_MAP).map(([group, names]) => [
          group,
          Object.fromEntries(
            names.map(name => [
              name,
              (...args) => {
                calls.push({ name: `${group}.${name}`, args });
                return 1;
              },
            ])
          ),
        ])
      );
      const compiled = createStudioCartFunction(source);
      const cart = runInNewContext(`(${compiled.toString()})()`, {
        nova64,
        print() {
          throw new Error('The cart called browser print');
        },
      });
      cart.init();
      cart.update(1 / 60);
      cart.draw();
      assert.ok(calls.some(call => call.name === 'scene.createCube'));
      assert.ok(calls.some(call => call.name === 'scene.createPlane'));
      assert.ok(calls.some(call => call.name === 'draw.print' && call.args[0] === 'Score: 0'));
    }
  );

  runner.test('Studio accepts the module shape the old README documented', () => {
    // nova64@0.5.3's README showed `export function init()`, so that form is
    // everywhere — in copied snippets and in carts generated by assistants that
    // read it. It must RUN, not merely fail with a nicer message.
    const cart = executeStudioCartCode(
      ['export function init() { return 1; }', 'export function update(dt) {}', 'export function draw() {}'].join(
        '\n'
      )
    );
    assert.equal(typeof cart.init, 'function');
    assert.equal(typeof cart.update, 'function');
    assert.equal(typeof cart.draw, 'function');
    assert.equal(cart.init(), 1);

    // Trailing export lists, `export default` and exported bindings too.
    const list = executeStudioCartCode(
      'function init() { return 2; }\nfunction draw() {}\nexport { init, draw };'
    );
    assert.equal(list.init(), 2);
    assert.equal(executeStudioCartCode('export default function init() { return 3; }').init(), 3);
    assert.equal(
      executeStudioCartCode('export const STEP = 4;\nfunction init() { return STEP; }').init(),
      4
    );
  });

  runner.test('Studio module syntax errors explain the script contract', () => {
    // `import` is still refused: unlike `export` (a declaration modifier that can
    // be dropped without changing behaviour), stripping an import would leave the
    // cart referencing bindings that were never created.
    for (const source of ["import cart from './cart.js'"]) {
      assert.throws(
        () => createStudioCartFunction(source),
        error =>
          error instanceof SyntaxError &&
          /studio/i.test(error.message) &&
          /without.*import.*export/i.test(error.message)
      );
    }
    // A genuine syntax error still reports against the original source.
    assert.throws(
      () => createStudioCartFunction('function init() { oops('),
      error => error instanceof SyntaxError && /Invalid Studio cart syntax/.test(error.message)
    );
    // The diagnostic must not rewrite strings/comments containing module keywords.
    const cart = executeStudioCartCode(`
      // export function init() {}
      function draw() { return 'export function init() {}'; }
    `);
    assert.equal(cart.draw(), 'export function init() {}');

    // Template literals and nested braces must survive the rewrite too.
    const tricky = executeStudioCartCode(
      [
        'const msg = `',
        'export function init(){}`;',
        'export function init() { return msg.trim(); }',
      ].join('\n')
    );
    assert.equal(tricky.init(), 'export function init(){}');
    assert.equal(
      executeStudioCartCode('function init() { const o = {}; o.export = 9; return o.export; }').init(),
      9
    );

    // A cart that already parses is never rewritten.
    const valid = 'function init() { return 1; }';
    assert.equal(stripTopLevelExports(valid), valid);
  });

  runner.test('Game Studio executor allows carts to destructure namespaced draw APIs', () => {
    const previousNova64 = globalThis.nova64;
    const previousCls = globalThis.cls;

    globalThis.cls = () => {};
    globalThis.nova64 = {
      draw: {
        cls: () => 'cleared',
        print: () => 'printed',
      },
    };

    try {
      const cart = executeStudioCartCode(`
        const { cls, print } = nova64.draw;

        function init() {
          cls();
          print('ok');
        }

        function update(dt) {
          return dt;
        }
      `);

      Assert.isFunction(cart.init, 'init should be returned');
      Assert.isFunction(cart.update, 'update should be returned');
      Assert.doesNotThrow(() => cart.init(), 'namespaced destructuring should not collide');
    } finally {
      if (previousNova64 === undefined) delete globalThis.nova64;
      else globalThis.nova64 = previousNova64;

      if (previousCls === undefined) delete globalThis.cls;
      else globalThis.cls = previousCls;
    }
  });

  runner.test('Game Studio executor still resolves legacy global API identifiers', () => {
    const previousCreateCube = globalThis.createCube;
    globalThis.createCube = () => ({ id: 'cube' });

    try {
      const cart = executeStudioCartCode(`
        let cube;

        function init() {
          cube = createCube();
        }

        function draw() {
          return cube.id;
        }
      `);

      cart.init();
      Assert.equals(cart.draw(), 'cube', 'legacy global createCube should resolve');
    } finally {
      if (previousCreateCube === undefined) delete globalThis.createCube;
      else globalThis.createCube = previousCreateCube;
    }
  });

  return runner.runAll();
}

if (process.argv[1] && process.argv[1].endsWith('test-studio-executor.js')) {
  runStudioExecutorTests().then(results => {
    process.exit(results.failed > 0 ? 1 : 0);
  });
}
