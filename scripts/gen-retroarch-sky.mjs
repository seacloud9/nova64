#!/usr/bin/env node
// Embed the web sky shaders, presets and constructors in the native QuickJS/GL host.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import {
  NOISE_GLSL,
  GRADIENT_FRAG,
  SPACE_FRAG,
  STAR_VERT,
  STAR_FRAG,
} from '../runtime/sky-shaders.js';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { buildSync } = createRequire(require.resolve('vite/package.json'))('esbuild');
const api = fs.readFileSync(path.join(root, 'runtime/api-skybox.js'), 'utf8');
function extractFunction(name) {
  const start = api.indexOf(`  function ${name}(`);
  if (start < 0) throw new Error(`Missing web sky function ${name}`);
  const end = api.indexOf('\n  }', start);
  return api.slice(start, end + 4);
}
function extractPresets(name) {
  const start = api.indexOf(`  const ${name} = {`);
  if (start < 0) throw new Error(`Missing ${name}`);
  return api.slice(start, api.indexOf('\n  };', start) + 5);
}
const functions = ['createGradientSkybox', 'createSpaceSkybox', 'createSkyPreset', 'getSkyPresets'];
const compat = fs
  .readFileSync(path.join(root, 'retroarch/skybox-compat.js'), 'utf8')
  .replace(
    '/* WEB_SKY_CONSTRUCTORS */',
    [
      extractPresets('SKY_PRESETS'),
      extractPresets('ENV_PRESETS'),
      ...functions.map(extractFunction),
    ].join('\n')
  );
const js = buildSync({
  stdin: { contents: compat, resolveDir: root, sourcefile: 'native-skybox.js' },
  bundle: true,
  format: 'iife',
  platform: 'neutral',
  target: 'es2020',
  minify: true,
  write: false,
}).outputFiles[0].text;
const uniforms = [
  ...new Map(
    [...`${GRADIENT_FRAG}\n${SPACE_FRAG}`.matchAll(/uniform (float|vec3) (\w+);/g)].map(m => [
      m[2],
      { name: m[2], size: m[1] === 'vec3' ? 3 : 1 },
    ])
  ).values(),
];
const cString = s =>
  s
    .split('\n')
    .map(line => JSON.stringify(line + '\n'))
    .join('\n');
function frag(source) {
  return (
    '#version 300 es\nprecision highp float;\nin vec2 v_ndc;\nuniform mat4 u_inv_vp;\nuniform float u_rotation;\nuniform int u_output_srgb;\nuniform int u_bake;\nout vec4 fragColor;\n' +
    NOISE_GLSL.replace(/\bnoise3\b/g, 'nova_noise3') +
    source
      .replace(/\bnoise3\b/g, 'nova_noise3')
      .replace('varying vec3 vDir;', '')
      .replace(
        'void main() {',
        `void main() {
    vec4 world = u_inv_vp * vec4(v_ndc, 1.0, 1.0);
    vec3 vDir = world.xyz / world.w;
    if (u_bake != 0) {
      float lon = v_ndc.x * 3.14159265359;
      float lat = v_ndc.y * 1.57079632679;
      vDir = vec3(cos(lat)*cos(lon), sin(lat), cos(lat)*sin(lon));
    }
    vDir = mat3(cos(u_rotation),0.0,sin(u_rotation), 0.0,1.0,0.0, -sin(u_rotation),0.0,cos(u_rotation)) * vDir;`
      )
      .replace(
        /gl_FragColor = vec4\(([^;]+), 1\.0\);/,
        `vec3 outputColor = max($1, vec3(0.0));
    fragColor = vec4(outputColor, 1.0);`
      )
  );
}
const shaders = {
  nova_sky_gradient_frag: frag(GRADIENT_FRAG),
  nova_sky_space_frag: frag(SPACE_FRAG),
  nova_sky_star_vert:
    '#version 300 es\nprecision highp float;\nin vec3 position;\nin vec3 color;\nuniform mat4 modelViewMatrix;\nuniform mat4 projectionMatrix;\n' +
    STAR_VERT.replaceAll('attribute ', 'in ').replaceAll('varying ', 'out '),
  nova_sky_star_frag:
    '#version 300 es\nprecision highp float;\nout vec4 fragColor;\n' +
    STAR_FRAG.replaceAll('varying ', 'in ').replaceAll('gl_FragColor', 'fragColor'),
};
let header = '// GENERATED by scripts/gen-retroarch-sky.mjs. Do not edit.\n';
header += `#define NOVA_SKY_UNIFORM_COUNT ${uniforms.length}\n`;
header +=
  'static const struct { const char *name; int size; } nova_sky_uniforms[] = {\n' +
  uniforms.map(u => `   {"${u.name}", ${u.size}},`).join('\n') +
  '\n};\n';
for (const [name, source] of Object.entries({ ...shaders, nova_sky_compat_js: js }))
  header += `static const char ${name}[] =\n${cString(source)};\n`;
const out = path.join(root, 'retroarch/generated/sky.h');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== header)
    throw new Error('Native sky header is stale: node scripts/gen-retroarch-sky.mjs');
  console.log('Native sky header is up to date');
} else {
  fs.writeFileSync(out, header);
  console.log('Wrote retroarch/generated/sky.h');
}
