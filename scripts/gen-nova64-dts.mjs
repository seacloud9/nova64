#!/usr/bin/env node
/**
 * Generate cart-facing Nova64 TypeScript declarations for the desktop Monaco
 * editor, from the canonical namespace map in runtime/namespace.js.
 *
 * Names are accurate (source of truth); signatures are intentionally loose
 * (`(...args: any[]): any`) so we never assert an incorrect type. Emits
 * apps/desktop/src/dev/nova64-types.js exporting the .d.ts as a string.
 *
 * Run:  node scripts/gen-nova64-dts.mjs
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NAMESPACE_MAP } from '../runtime/namespace.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, '..', 'apps', 'desktop', 'src', 'dev', 'nova64-types.js');

const ident = /^[A-Za-z_$][\w$]*$/;
const cap = s => s.charAt(0).toUpperCase() + s.slice(1);

const namespaces = Object.entries(NAMESPACE_MAP);
const allNames = new Set();

const interfaces = namespaces
  .map(([ns, names]) => {
    const members = [...new Set(names)]
      .filter(n => ident.test(n))
      .map(n => {
        allNames.add(n);
        return `  ${n}(...args: any[]): any;`;
      })
      .join('\n');
    return `interface Nova64${cap(ns)} {\n${members}\n}`;
  })
  .join('\n\n');

const apiMembers = namespaces.map(([ns]) => `  ${ns}: Nova64${cap(ns)};`).join('\n');
const globals = [...allNames]
  .sort()
  .map(n => `declare function ${n}(...args: any[]): any;`)
  .join('\n');

const dts = `// Nova64 cart API — GENERATED from runtime/namespace.js (do not edit by hand).
// Regenerate with: node scripts/gen-nova64-dts.mjs

/** Cart lifecycle hooks. */
declare function init(): void | Promise<void>;
declare function update(dt: number): void;
declare function draw(): void;

${interfaces}

interface Nova64Api {
${apiMembers}
}

/** Grouped Nova64 API. Prefer nova64.<group>.<fn>() in new carts. */
declare const nova64: Nova64Api;

// Flat globals (also available bare in carts).
${globals}
`;

const module = `/* eslint-disable */
// GENERATED by scripts/gen-nova64-dts.mjs — do not edit by hand.
export const NOVA64_DTS = ${JSON.stringify(dts)};
`;

writeFileSync(OUT, module, 'utf8');
console.log(
  `Wrote ${OUT} (${namespaces.length} namespaces, ${allNames.size} functions, ${dts.length} chars)`
);
